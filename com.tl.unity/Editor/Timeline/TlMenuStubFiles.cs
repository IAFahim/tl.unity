using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.Compilation;

namespace Tl.Unity.Editor
{
    [InitializeOnLoad]
#if UNITY_7000_0_OR_NEWER
    [global::Unity.Scripting.LifecycleManagement.NoAutoStaticsCleanup]
#endif
    public static class TlMenuStubFiles
    {
        public const string Folder = "Assets/Tl Generated/Editor";
        const string Header = "// <auto-generated by Tl: one menu entry for the Timeline + menu; Tl rewrites or deletes this file>";
        const string MirrorSuffix = "_TlData";
        const string StubSuffix = "_TlMenu";

        static TlMenuStubFiles()
        {
            if (AssetDatabase.IsAssetImportWorkerProcess())
                return;
            EditorApplication.update += SyncOnce;
        }

        static void SyncOnce()
        {
            if (EditorApplication.isCompiling || EditorApplication.isUpdating)
                return;
            EditorApplication.update -= SyncOnce;
            Sync();
        }

        public static bool Sync()
        {
            var wanted = Wanted();
            var changed = false;
            if (wanted.Count > 0 && !Directory.Exists(Folder))
                Directory.CreateDirectory(Folder);
            foreach (var pair in wanted)
            {
                var path = Folder + "/" + pair.Key;
                if (File.Exists(path) && File.ReadAllText(path) == pair.Value)
                    continue;
                File.WriteAllText(path, pair.Value, new UTF8Encoding(false));
                changed = true;
            }
            if (Directory.Exists(Folder))
                foreach (var path in Directory.GetFiles(Folder, "*" + StubSuffix + ".cs"))
                {
                    var name = Path.GetFileName(path);
                    if (wanted.ContainsKey(name) || !(File.ReadLines(path).FirstOrDefault() ?? "").StartsWith(Header, StringComparison.Ordinal))
                        continue;
                    AssetDatabase.DeleteAsset(path.Replace('\\', '/'));
                    changed = true;
                }
            if (changed)
                AssetDatabase.Refresh();
            return changed;
        }

        public static Dictionary<string, string> Wanted()
        {
            var result = new Dictionary<string, string>(StringComparer.Ordinal);
            var inAssets = AssembliesCompiledFromAssets();
            foreach (var type in TypeCache.GetTypesDerivedFrom<TlClipData>())
            {
                if (type.IsAbstract || type.Namespace != "Tl.Generated" || !type.Name.EndsWith(MirrorSuffix, StringComparison.Ordinal) || !inAssets.Contains(type.Assembly.GetName().Name))
                    continue;
                var menu = ((TlClipData)Activator.CreateInstance(type)).MenuName;
                var stub = type.Name.Substring(0, type.Name.Length - MirrorSuffix.Length) + StubSuffix;
                result[stub + ".cs"] = Text(stub, menu, type.FullName + ", " + type.Assembly.GetName().Name);
            }
            return result;
        }

        public static string Text(string stub, string menu, string mirror)
        {
            var text = new StringBuilder();
            text.Append(Header).Append('\n');
            text.Append("namespace Tl.Generated\n{\n");
            text.Append("    [global::System.ComponentModel.DisplayName(").Append(Literal(menu)).Append(")]\n");
            text.Append("    public sealed class ").Append(stub).Append(" : global::Tl.Unity.TlMenuTrack\n    {\n");
            text.Append("        public override global::Tl.Unity.TlClipData CreateTemplate() => global::Tl.Unity.Editor.TlMenuStubs.Template(").Append(Literal(mirror)).Append(");\n");
            text.Append("    }\n}\n");
            return text.ToString();
        }

        static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        static bool IsPack(string file)
        {
            if (!file.StartsWith("Packages/com.tl.pack.", StringComparison.Ordinal))
                return false;
            var slash = file.IndexOf('/', "Packages/".Length);
            return slash > 0 && !file.Substring(slash).StartsWith("/Tests/", StringComparison.Ordinal);
        }

        static HashSet<string> AssembliesCompiledFromAssets()
        {
            var names = new HashSet<string>(StringComparer.Ordinal);
            foreach (var assembly in CompilationPipeline.GetAssemblies(AssembliesType.Editor))
                if (assembly.sourceFiles.Any(file => file.StartsWith("Assets/", StringComparison.Ordinal) || IsPack(file)))
                    names.Add(assembly.name);
            return names;
        }
    }

    public static class TlMenuStubs
    {
        public static TlClipData Template(string mirror)
        {
            return (TlClipData)Activator.CreateInstance(Type.GetType(mirror, true));
        }
    }
}
