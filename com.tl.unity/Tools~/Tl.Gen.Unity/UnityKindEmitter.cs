using System.Text;
using Microsoft.CodeAnalysis;
using Tl.Gen.CSharp.Model;

namespace Tl.Gen.Unity
{
    internal sealed class UnityKindInfo
    {
        public UnityKindInfo(KindDecl decl, int registry, int valueBytes, int entryBytes, string capacity, string ns, string signature)
        {
            Decl = decl;
            Registry = registry;
            ValueBytes = valueBytes;
            EntryBytes = entryBytes;
            Capacity = capacity;
            Namespace = ns;
            Signature = signature;
        }

        public readonly KindDecl Decl;
        public readonly int Registry;
        public readonly int ValueBytes;
        public readonly int EntryBytes;
        public readonly string Capacity;
        public readonly string Namespace;
        public readonly string Signature;

        public string Name => Decl.Name;
        public string Entry => "global::" + Namespace + "." + Decl.Name + "Entry";
        public string Active => "global::" + Namespace + "." + Decl.Name + "Active";
        public string Enabled => "global::" + Namespace + "." + Decl.Name + "Enabled";
        public bool Pulses => Decl.Accepts != 0;
    }

    internal static class UnityKindEmitter
    {
        internal const string FramesType = "global::TlUnityGenerated.TlUnityFrames";

        static void W(StringBuilder writer, string text)
        {
            writer.Append(text).Append('\n');
        }

        internal static string NamespaceOf(string typeName)
        {
            var bare = typeName.StartsWith("global::") ? typeName.Substring(8) : typeName;
            var dot = bare.LastIndexOf('.');
            return dot < 0 ? "" : bare.Substring(0, dot);
        }

        static string Sanitize(string typeName)
        {
            var builder = new StringBuilder();
            foreach (var c in typeName)
                builder.Append(char.IsLetterOrDigit(c) ? c : '_');
            return builder.ToString();
        }

        internal static string Signature(IReadOnlyList<SystemAssignment> assignments, KindDecl kind)
        {
            var parts = new List<(string consumer, string method, int trigger)>();
            foreach (var assignment in assignments)
                foreach (var consumer in assignment.Consumers)
                    foreach (var feeder in consumer.Feeders)
                        if (feeder.KindName == kind.Name)
                            parts.Add((feeder.ConsumerMetadata, feeder.MethodName, (int)feeder.Trigger));
            parts.Sort((a, b) =>
            {
                var by = string.CompareOrdinal(a.consumer, b.consumer);
                return by != 0 ? by : string.CompareOrdinal(a.method, b.method);
            });
            var list = new List<string>();
            foreach (var p in parts)
                list.Add(p.consumer + "." + p.method + ":" + p.trigger);
            return string.Join("\n", list);
        }

        static ConsumerMethod? FoldOf(SystemConsumer consumer)
        {
            foreach (var method in consumer.Methods)
                if (method.Kind == ConsumerMethodKind.Fold)
                    return method;
            return null;
        }

        static int LaneBytes(SystemConsumer consumer)
        {
            var fold = FoldOf(consumer);
            if (fold == null)
                return 0;
            var bytes = 0;
            foreach (var size in fold.FoldSizes)
                bytes += size;
            return bytes;
        }

        static string FrameName(int assignment, int consumer)
        {
            return "Frame_" + assignment + "_" + consumer;
        }

        internal static string EmitKinds(IReadOnlyList<SystemAssignment> assignments, IReadOnlyList<UnityKindInfo> kinds, string id)
        {
            var writer = new StringBuilder();
            W(writer, "// <auto-generated/>");
            W(writer, "using Unity.Entities;");
            W(writer, "using Unity.Burst;");
            W(writer, "using Unity.Collections;");
            foreach (var group in GroupByNamespace(kinds))
            {
                W(writer, "namespace " + (group.Key.Length == 0 ? "TlUnityGenerated" : group.Key));
                W(writer, "{");
                foreach (var kind in group.Value)
                {
                    W(writer, "[InternalBufferCapacity(" + kind.Capacity + ")]");
                    W(writer, "[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential, Size = " + kind.EntryBytes + ")]");
                    W(writer, "public struct " + kind.Name + "Entry : IBufferElementData");
                    W(writer, "{");
                    W(writer, "public ushort Timeline; public ushort Step; public byte Slot; public byte Feeder; public global::Tl.KindEntryFlags Flags; public byte Reserved;");
                    W(writer, "}");
                    W(writer, "public struct " + kind.Name + "Active : IComponentData, IEnableableComponent { }");
                    W(writer, "public struct " + kind.Name + "Enabled : IComponentData, IEnableableComponent { }");
                    W(writer, "public static class " + kind.Name + "Kind");
                    W(writer, "{");
                    W(writer, "public const int Id = " + kind.Registry + ";");
                    W(writer, "public const int InlineCapacity = " + kind.Capacity + ";");
                    W(writer, "public static global::Unity.Entities.ComponentType[] Types { get { return new global::Unity.Entities.ComponentType[] { typeof(" + kind.Name + "Entry), typeof(" + kind.Name + "Active), typeof(" + kind.Name + "Enabled) }; } }");
                    W(writer, "public static void Init(global::Unity.Entities.EntityManager entities, global::Unity.Entities.Entity entity) { entities.SetComponentEnabled<" + kind.Name + "Active>(entity, false); }");
                    if (kind.Pulses)
                        W(writer, "public static global::Tl.Unity.KindPulses<" + kind.Decl.ValueTypeName + "> Pulses(global::Tl.Unity.KindPulseWriter writer) { return new global::Tl.Unity.KindPulses<" + kind.Decl.ValueTypeName + ">(writer, Id); }");
                    W(writer, "}");
                }
                W(writer, "}");
            }
            W(writer, "namespace TlUnityGenerated");
            W(writer, "{");
            EmitModule(writer, assignments, kinds, id);
            EmitFrames(writer, assignments);
            W(writer, "}");
            return writer.ToString().Replace("\r\n", "\n");
        }

        static SortedDictionary<string, List<UnityKindInfo>> GroupByNamespace(IReadOnlyList<UnityKindInfo> kinds)
        {
            var map = new SortedDictionary<string, List<UnityKindInfo>>(System.StringComparer.Ordinal);
            foreach (var kind in kinds)
            {
                if (!map.TryGetValue(kind.Namespace, out var list))
                    map[kind.Namespace] = list = new List<UnityKindInfo>();
                list.Add(kind);
            }
            return map;
        }

        static void EmitModule(StringBuilder writer, IReadOnlyList<SystemAssignment> assignments, IReadOnlyList<UnityKindInfo> kinds, string id)
        {
            var folds = new List<(SystemConsumer consumer, int assignment, int index)>();
            for (var a = 0; a < assignments.Count; a++)
                for (var c = 0; c < assignments[a].Consumers.Count; c++)
                    if (FoldOf(assignments[a].Consumers[c]) != null && !assignments[a].Consumers[c].IsMarker)
                        folds.Add((assignments[a].Consumers[c], a, c));
            W(writer, "public sealed class TlUnityModule_" + id + " : global::Tl.ITlModule, global::Tl.Unity.IKindModule");
            W(writer, "{");
            W(writer, "public int PairCount { get { return " + folds.Count + "; } }");
            W(writer, "public ulong PairKey(int index)");
            W(writer, "{");
            W(writer, "switch (index)");
            W(writer, "{");
            for (var i = 0; i < folds.Count; i++)
                W(writer, "case " + i + ": return " + folds[i].consumer.PairKey + "UL;");
            W(writer, "default: return 0UL;");
            W(writer, "}");
            W(writer, "}");
            W(writer, "public int FoldLaneBytes(int index)");
            W(writer, "{");
            W(writer, "switch (index)");
            W(writer, "{");
            for (var i = 0; i < folds.Count; i++)
                W(writer, "case " + i + ": return " + LaneBytes(folds[i].consumer) + ";");
            W(writer, "default: return 0;");
            W(writer, "}");
            W(writer, "}");
            W(writer, "public int FoldLaneOffset(int index)");
            W(writer, "{");
            W(writer, "switch (index)");
            W(writer, "{");
            for (var i = 0; i < folds.Count; i++)
            {
                var sum = 0;
                for (var k = 0; k < i; k++)
                    if (folds[k].consumer.PairKey == folds[i].consumer.PairKey)
                        sum += LaneBytes(folds[k].consumer);
                W(writer, "case " + i + ": return " + sum + ";");
            }
            W(writer, "default: return 0;");
            W(writer, "}");
            W(writer, "}");
            W(writer, "public unsafe void FoldStep(int index, byte* track, byte* first, byte* second, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, byte* lane)");
            W(writer, "{");
            W(writer, "switch (index)");
            W(writer, "{");
            for (var i = 0; i < folds.Count; i++)
            {
                var fold = folds[i];
                W(writer, "case " + i + ":");
                W(writer, "{");
                W(writer, "TlUnityFrames." + FrameName(fold.assignment, fold.index) + "(track, first, second == first ? null : second, blend, tick, windowLength, withinClip, trackIndex, duration, direction, global::Tl.FrameFlags.None, out var __t, out var __c, out var __frame);");
                var method = FoldOf(fold.consumer)!;
                for (var o = 0; o < method.Params.Count; o++)
                    W(writer, method.Params[o].TypeName + " __out" + o + " = default;");
                var outs = new List<string>();
                for (var o = 0; o < method.Params.Count; o++)
                    outs.Add("out __out" + o);
                W(writer, fold.consumer.ConsumerTypeName + ".Fold(in __frame, " + string.Join(", ", outs) + ");");
                var offset = 0;
                for (var o = 0; o < method.Params.Count; o++)
                {
                    W(writer, "*(" + method.Params[o].TypeName + "*)(lane + " + offset + ") = __out" + o + ";");
                    offset += method.FoldSizes[o];
                }
                W(writer, "return;");
                W(writer, "}");
            }
            W(writer, "default: return;");
            W(writer, "}");
            W(writer, "}");
            W(writer, "public void Register(global::Tl.Unity.KindRegistry registry)");
            W(writer, "{");
            foreach (var kind in kinds)
                W(writer, "registry.Add(new global::Tl.Unity.KindDescriptor(\"" + kind.Name + "\", typeof(" + kind.Entry + "), typeof(" + kind.Active + "), typeof(" + kind.Enabled + "), " + kind.ValueBytes + ", " + kind.EntryBytes + ", \"" + kind.Signature.Replace("\\", "\\\\").Replace("\n", "\\n").Replace("\"", "\\\"") + "\"));");
            W(writer, "}");
            W(writer, "}");
        }

        static void EmitFrames(StringBuilder writer, IReadOnlyList<SystemAssignment> assignments)
        {
            W(writer, "public static unsafe class TlUnityFrames");
            W(writer, "{");
            for (var a = 0; a < assignments.Count; a++)
                for (var c = 0; c < assignments[a].Consumers.Count; c++)
                {
                    var consumer = assignments[a].Consumers[c];
                    if (consumer.IsMarker)
                        continue;
                    W(writer, "public static void " + FrameName(a, c) + "(byte* trackPtr, byte* firstPtr, byte* secondPtr, float blend, ushort tick, ushort windowLength, ushort withinClip, ushort trackIndex, ushort duration, sbyte direction, global::Tl.FrameFlags extra, out " + consumer.TrackTypeName + " track, out " + consumer.ClipTypeName + " clip, out global::Tl.Frame<" + consumer.TrackTypeName + ", " + consumer.ClipTypeName + "> frame)");
                    W(writer, "{");
                    W(writer, "track = *(" + consumer.TrackTypeName + "*)trackPtr;");
                    W(writer, "clip = *(" + consumer.ClipTypeName + "*)firstPtr;");
                    W(writer, "if (secondPtr != null)");
                    W(writer, "{");
                    W(writer, consumer.ClipTypeName + " __second = *(" + consumer.ClipTypeName + "*)secondPtr;");
                    if (consumer.TrackBlendable)
                        W(writer, "track.Blend(in clip, in __second, blend, out clip);");
                    else
                        W(writer, "throw new global::System.InvalidOperationException(\"" + consumer.ConsumerTypeName.Replace("global::", "") + ": blended window without IBlend.\");");
                    W(writer, "}");
                    W(writer, "var __flags = (direction < 0 ? global::Tl.FrameFlags.Reverse : global::Tl.FrameFlags.None) | extra;");
                    W(writer, "if (withinClip == 0) __flags |= global::Tl.FrameFlags.ClipStart;");
                    W(writer, "if (withinClip == (ushort)(windowLength - 1)) __flags |= global::Tl.FrameFlags.ClipEnd;");
                    W(writer, "if (tick == 0) __flags |= global::Tl.FrameFlags.TimelineStart;");
                    W(writer, "if (tick == (ushort)(duration - 1)) __flags |= global::Tl.FrameFlags.TimelineEnd;");
                    W(writer, "frame = new global::Tl.Frame<" + consumer.TrackTypeName + ", " + consumer.ClipTypeName + ">(in track, in clip, tick, windowLength, withinClip, trackIndex, __flags);");
                    W(writer, "}");
                }
            W(writer, "}");
        }
    }
}
