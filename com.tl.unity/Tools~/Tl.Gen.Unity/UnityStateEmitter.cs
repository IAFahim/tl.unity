using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Tl.Gen.Unity
{
    internal static class UnityStateEmitter
    {
        internal const string FileName = "TlUnity.States.g.cs";

        internal static IReadOnlyList<string> Emit(SourceProductionContext context, IReadOnlyList<INamedTypeSymbol> states, Compilation compilation)
        {
            var names = new List<string>();
            if (states.Count == 0)
                return names;
            var component = compilation.GetTypeByMetadataName("Unity.Entities.IComponentData");
            if (component is null)
                return names;
            var writer = new StringBuilder();
            writer.Append("// <auto-generated/>\n");
            foreach (var state in states)
            {
                var full = state.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var already = false;
                foreach (var face in state.AllInterfaces)
                    if (SymbolEqualityComparer.Default.Equals(face, component))
                        already = true;
                if (already)
                    continue;
                if (state.ContainingType is not null || !IsPartial(state))
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        new DiagnosticDescriptor("TLUNITY9107", "TlState needs a partial top-level struct", "[TlState] struct '{0}' must be a partial struct declared directly in a namespace; Tl adds IComponentData to it.", "Tl.Unity", DiagnosticSeverity.Error, true),
                        state.Locations.FirstOrDefault() ?? Location.None, full));
                    continue;
                }
                var ns = state.ContainingNamespace is { IsGlobalNamespace: false } space ? space.ToDisplayString() : null;
                if (ns != null)
                    writer.Append("namespace ").Append(ns).Append("\n{\n");
                writer.Append("partial struct ").Append(state.Name).Append(" : global::Unity.Entities.IComponentData\n{\n}\n");
                if (ns != null)
                    writer.Append("}\n");
                names.Add(full);
            }
            if (names.Count != 0)
                context.AddSource(FileName, SourceText.From(writer.ToString(), Encoding.UTF8));
            return names;
        }

        static bool IsPartial(INamedTypeSymbol type)
        {
            foreach (var reference in type.DeclaringSyntaxReferences)
                if (reference.GetSyntax() is TypeDeclarationSyntax syntax)
                    foreach (var modifier in syntax.Modifiers)
                        if (modifier.Text == "partial")
                            return true;
            return false;
        }
    }
}
