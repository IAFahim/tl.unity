using System.Text;

namespace Tl.Gen.Unity
{
    internal static class UnitySystemEmitter
    {
        internal static string FileName(UnitySystemModel model)
        {
            return "TlUnity." + model.SystemTypeName + ".g.cs";
        }

        internal static string Emit(UnitySystemModel model)
        {
            var ns = model.Namespace.StartsWith("global::") ? model.Namespace.Substring(8) : model.Namespace;
            var writer = new StringBuilder();
            writer.Append("// <auto-generated/>\n");
            writer.Append("using Unity.Burst;\n");
            writer.Append("using Unity.Collections;\n");
            writer.Append("using Unity.Entities;\n");
            writer.Append("using Unity.Jobs;\n");
            writer.Append("namespace ");
            writer.Append(ns);
            writer.Append("\n{\n");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var column = model.Columns[i];
                writer.Append("public struct ");
                writer.Append(ComponentName(model, column));
                writer.Append(" : IComponentData { public ");
                writer.Append(column.ElementTypeName);
                writer.Append(" Value; }\n");
            }
            writer.Append("[BurstCompile]\n");
            writer.Append("public partial struct ");
            writer.Append(model.SystemTypeName);
            writer.Append("ChunkJob : IJobChunk\n{\n");
            writer.Append("public global::Tl.LibraryView View;\n");
            writer.Append("public BufferTypeHandle<global::Tl.Unity.Playback> PlaybackHandle;\n");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var column = model.Columns[i];
                writer.Append("public ComponentTypeHandle<");
                writer.Append(ComponentName(model, column));
                writer.Append("> ");
                writer.Append(column.Name);
                writer.Append("Handle;\n");
            }
            writer.Append("public unsafe void Execute(in ArchetypeChunk chunk, int unfilteredChunkIndex, bool useEnabledMask, in global::Unity.Burst.Intrinsics.v128 chunkEnabledMask)\n{\n");
            writer.Append("var playbacks = chunk.GetBufferAccessor(ref PlaybackHandle);\n");
            writer.Append("for (var row = 0; row < chunk.Count; row++)\n{\n");
            writer.Append("var slots = playbacks[row];\n");
            writer.Append("for (var s = 0; s < slots.Length; s++)\n{\n");
            writer.Append("var timeline = global::Tl.Unity.TimelineKernel.GetTimeline(in View, slots[s].Timeline);\n");
            writer.Append("if (timeline == null) continue;\n");
            writer.Append("if (global::Tl.LibraryViewReader.StageAt(timeline, slots[s].Tick) == null) continue;\n");
            writer.Append("RunStep(row, s);\n");
            writer.Append("}\n}\n}\n");
            writer.Append("partial void RunStep(int row, int slotIndex);\n");
            writer.Append("}\n");
            writer.Append("public static partial class TimelineJobs\n{\n");
            writer.Append("public static JobHandle ");
            writer.Append(model.SystemTypeName);
            writer.Append("(ref SystemState state, global::Tl.LibraryView view");
            for (var i = 0; i < model.Contexts.Count; i++)
            {
                writer.Append(", ");
                writer.Append(model.Contexts[i].TypeName);
                writer.Append(" ");
                writer.Append(model.Contexts[i].Name);
            }
            writer.Append(", JobHandle dependsOn)\n{\n");
            writer.Append("var query = state.EntityManager.CreateEntityQuery(ComponentType.ReadOnly<global::Tl.Unity.Playback>()");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                writer.Append(", ");
                writer.Append(model.Columns[i].ReadOnly ? "ComponentType.ReadOnly<" : "ComponentType.ReadWrite<");
                writer.Append(ComponentName(model, model.Columns[i]));
                writer.Append(">()");
            }
            writer.Append(");\n");
            writer.Append("var job = new ");
            writer.Append(model.SystemTypeName);
            writer.Append("ChunkJob { View = view, PlaybackHandle = state.GetBufferTypeHandle<global::Tl.Unity.Playback>(true)");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                writer.Append(", ");
                writer.Append(model.Columns[i].Name);
                writer.Append("Handle = state.GetComponentTypeHandle<");
                writer.Append(ComponentName(model, model.Columns[i]));
                writer.Append(">(");
                writer.Append(model.Columns[i].ReadOnly ? "true" : "false");
                writer.Append(")");
            }
            writer.Append(" };\n");
            writer.Append("return job.ScheduleParallel(query, dependsOn);\n");
            writer.Append("}\n}\n}\n");
            return writer.ToString().Replace("\r\n", "\n");
        }

        static string ComponentName(UnitySystemModel model, UnityColumn column)
        {
            return model.SystemTypeName + "_" + column.Name + "Data";
        }
    }
}
