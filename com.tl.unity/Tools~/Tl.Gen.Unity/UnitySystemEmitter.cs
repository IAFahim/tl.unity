using System.Text;

namespace Tl.Gen.Unity
{
    internal static class UnitySystemEmitter
    {
        internal static string FileName(UnitySystemModel model)
        {
            return "TlUnity." + model.SystemTypeName + ".g.cs";
        }

        internal static string Emit(UnitySystemModel model)
        {
            var ns = model.Namespace.StartsWith("global::") ? model.Namespace.Substring(8) : model.Namespace;
            var writer = new StringBuilder();
            writer.Append("// <auto-generated/>\n");
            writer.Append("using Unity.Burst;\n");
            writer.Append("using Unity.Collections;\n");
            writer.Append("using Unity.Entities;\n");
            writer.Append("using Unity.Jobs;\n");
            writer.Append("namespace ");
            writer.Append(ns);
            writer.Append("\n{\n");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var column = model.Columns[i];
                writer.Append("public struct ");
                writer.Append(ComponentName(model, column));
                writer.Append(" : IComponentData { public ");
                writer.Append(column.ElementTypeName);
                writer.Append(" Value; }\n");
            }
            writer.Append("[BurstCompile]\n");
            writer.Append("public partial struct ");
            writer.Append(model.SystemTypeName);
            writer.Append("ChunkJob : IJobChunk\n{\n");
            writer.Append("[global::Unity.Collections.LowLevel.Unsafe.NativeDisableUnsafePtrRestriction] public global::Tl.LibraryView View;\n");
            writer.Append("[ReadOnly] public BufferTypeHandle<global::Tl.Unity.Playback> PlaybackHandle;\n");
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var column = model.Columns[i];
                writer.Append(column.ReadOnly ? "[ReadOnly] public ComponentTypeHandle<" : "public ComponentTypeHandle<");
                writer.Append(ComponentName(model, column));
                writer.Append("> ");
                writer.Append(column.Name);
                writer.Append("Handle;\n");
            }
            writer.Append("public unsafe void Execute(in ArchetypeChunk chunk, int unfilteredChunkIndex, bool useEnabledMask, in global::Unity.Burst.Intrinsics.v128 chunkEnabledMask)\n{\n");
            writer.Append("var playbacks = chunk.GetBufferAccessor(ref PlaybackHandle);\n");
            writer.Append("for (var row = 0; row < chunk.Count; row++)\n{\n");
            writer.Append("var slots = playbacks[row];\n");
            writer.Append("for (var s = 0; s < slots.Length; s++)\n{\n");
            writer.Append("var timeline = global::Tl.Unity.TimelineKernel.GetTimeline(in View, slots[s].Timeline);\n");
            writer.Append("if (timeline == null) continue;\n");
            writer.Append("if (global::Tl.LibraryViewReader.StageAt(timeline, slots[s].Tick) == null) continue;\n");
            writer.Append("RunStep(row, s);\n");
            writer.Append("}\n}\n}\n");
            writer.Append("partial void RunStep(int row, int slotIndex);\n");
            writer.Append("}\n");
            var name = model.SystemTypeName;
            writer.Append("public static partial class TimelineJobs\n{\n");
            writer.Append("public struct ").Append(name).Append("\n{\n");
            writer.Append("EntityQuery _query;\n");
            writer.Append("BufferTypeHandle<global::Tl.Unity.Playback> _PlaybackHandle;\n");
            foreach (var column in model.Columns)
                writer.Append("ComponentTypeHandle<").Append(ComponentName(model, column)).Append("> _").Append(column.Name).Append("Handle;\n");
            writer.Append("public static ").Append(name).Append(" Create(ref SystemState state)\n{\n");
            writer.Append("var jobs = default(").Append(name).Append(");\n");
            writer.Append("var builder = new EntityQueryBuilder(Allocator.Temp).WithAll<global::Tl.Unity.Playback>();\n");
            foreach (var column in model.Columns)
                writer.Append("builder = builder.").Append(column.ReadOnly ? "WithAll<" : "WithAllRW<").Append(ComponentName(model, column)).Append(">();\n");
            writer.Append("jobs._query = builder.Build(ref state);\n");
            writer.Append("builder.Dispose();\n");
            writer.Append("jobs._PlaybackHandle = state.GetBufferTypeHandle<global::Tl.Unity.Playback>(true);\n");
            foreach (var column in model.Columns)
                writer.Append("jobs._").Append(column.Name).Append("Handle = state.GetComponentTypeHandle<").Append(ComponentName(model, column)).Append(">(").Append(column.ReadOnly ? "true" : "false").Append(");\n");
            writer.Append("return jobs;\n}\n");
            writer.Append("public JobHandle Schedule(ref SystemState state, global::Tl.LibraryView view");
            foreach (var context in model.Contexts)
                writer.Append(", ").Append(context.TypeName).Append(" ").Append(context.Name);
            writer.Append(", JobHandle dependsOn)\n{\n");
            writer.Append("_PlaybackHandle.Update(ref state);\n");
            foreach (var column in model.Columns)
                writer.Append("_").Append(column.Name).Append("Handle.Update(ref state);\n");
            writer.Append("var job = new ").Append(name).Append("ChunkJob { View = view, PlaybackHandle = _PlaybackHandle");
            foreach (var column in model.Columns)
                writer.Append(", ").Append(column.Name).Append("Handle = _").Append(column.Name).Append("Handle");
            writer.Append(" };\n");
            writer.Append("return job.ScheduleParallel(_query, dependsOn);\n");
            writer.Append("}\n}\n}\n}\n");
            return writer.ToString().Replace("\r\n", "\n");
        }

        static string ComponentName(UnitySystemModel model, UnityColumn column)
        {
            return model.SystemTypeName + "_" + column.Name + "Data";
        }
    }
}
