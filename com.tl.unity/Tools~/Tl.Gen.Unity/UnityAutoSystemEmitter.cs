using System.Text;

namespace Tl.Gen.Unity
{
    internal static class UnityAutoSystemEmitter
    {
        internal const string FileName = "TlUnity.AutoSystem.g.cs";

        internal static string Emit(UnitySystemModel model)
        {
            var name = model.SystemTypeName;
            var jobs = name + "_Jobs";
            var writer = new StringBuilder();
            writer.Append("// <auto-generated/>\n");
            writer.Append("[assembly: global::Unity.Entities.RegisterGenericSystemType(typeof(global::Tl.Unity.TlKindSystem<global::Tl.Generated.").Append(jobs).Append(">))]\n");
            writer.Append("namespace Tl.Generated\n{\n");
            writer.Append("public struct ").Append(jobs).Append(" : global::Tl.Unity.ITlKindJobs\n{\n");
            writer.Append("global::Tl.Generated.TimelineJobs.").Append(name).Append(" _jobs;\n");
            writer.Append("public void Create(ref global::Unity.Entities.SystemState state)\n{\n");
            writer.Append("_jobs = global::Tl.Generated.TimelineJobs.").Append(name).Append(".Create(ref state);\n}\n");
            writer.Append("public global::Unity.Jobs.JobHandle Schedule(ref global::Unity.Entities.SystemState state, global::Tl.LibraryView view, global::Tl.Unity.KindIndex index, bool forward, global::Unity.Jobs.JobHandle dependsOn)\n{\n");
            writer.Append("return _jobs.Schedule(ref state, view, index, forward, dependsOn);\n}\n");
            writer.Append("}\n}\n");
            return writer.ToString();
        }
    }
}
