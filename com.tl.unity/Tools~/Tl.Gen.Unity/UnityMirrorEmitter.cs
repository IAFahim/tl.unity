using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Tl.Gen.Unity
{
    internal static class UnityMirrorEmitter
    {
        internal const string FileName = "TlUnity.Clips.g.cs";
        static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat;

        internal static void Emit(SourceProductionContext context, CSharpCompilation compilation)
        {
            var clipAttribute = compilation.GetTypeByMetadataName("Tl.TlClipAttribute");
            var data = compilation.GetTypeByMetadataName("Tl.Unity.TlClipData");
            var baker = compilation.GetTypeByMetadataName("Tl.ITlBaker`1");
            var curve = compilation.GetTypeByMetadataName("Tl.TlCurve");
            var timelineRef = compilation.GetTypeByMetadataName("Tl.TlTimeline");
            var timelineId = compilation.GetTypeByMetadataName("Tl.TimelineId");
            var timelineAsset = compilation.GetTypeByMetadataName("UnityEngine.Timeline.TimelineAsset");
            if (timelineAsset is null)
            {
                timelineRef = null;
                timelineId = null;
            }
            var menuTrack = compilation.GetTypeByMetadataName("Tl.Unity.TlMenuTrack");
            if (clipAttribute is null || data is null || compilation.GetTypeByMetadataName("UnityEngine.AnimationCurve") is null)
                return;
            var clips = new List<(INamedTypeSymbol type, string menu)>();
            var bakers = new List<INamedTypeSymbol>();
            foreach (var tree in compilation.SyntaxTrees)
            {
                var model = compilation.GetSemanticModel(tree);
                foreach (var node in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
                {
                    if (model.GetDeclaredSymbol(node) is not INamedTypeSymbol type || type.TypeKind != TypeKind.Struct)
                        continue;
                    foreach (var attribute in type.GetAttributes())
                        if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, clipAttribute))
                        {
                            var menu = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string text ? text : type.Name;
                            if (!clips.Any(c => SymbolEqualityComparer.Default.Equals(c.type, type)))
                                clips.Add((type, menu));
                        }
                    if (baker is not null && !bakers.Contains(type, SymbolEqualityComparer.Default))
                        foreach (var face in type.AllInterfaces)
                            if (SymbolEqualityComparer.Default.Equals(face.OriginalDefinition, baker))
                                bakers.Add(type);
                }
            }
            if (clips.Count == 0)
                return;
            clips.Sort((a, b) => string.CompareOrdinal(a.type.ToDisplayString(Full), b.type.ToDisplayString(Full)));
            bakers.Sort((a, b) => string.CompareOrdinal(a.ToDisplayString(Full), b.ToDisplayString(Full)));
            var writer = new StringBuilder();
            writer.Append("// <auto-generated/>\n");
            writer.Append("namespace Tl.Generated\n{\n");
            foreach (var (type, menu) in clips)
            {
                EmitClip(writer, type, menu, bakers, baker, curve, timelineRef, timelineId);
                if (menuTrack is not null)
                    EmitMenu(writer, type, menu);
            }
            writer.Append("}\n");
            context.AddSource(FileName, SourceText.From(writer.ToString(), Encoding.UTF8));
        }

        static void EmitClip(StringBuilder writer, INamedTypeSymbol type, string menu, List<INamedTypeSymbol> bakers, INamedTypeSymbol? baker, INamedTypeSymbol? curve, INamedTypeSymbol? timelineRef, INamedTypeSymbol? timelineId)
        {
            var clip = type.ToDisplayString(Full);
            var name = MirrorName(type);
            var fields = new List<(string name, string kind, string type)>();
            foreach (var member in type.GetMembers().OfType<IFieldSymbol>())
            {
                if (member.IsStatic || member.IsConst || member.IsReadOnly || member.IsImplicitlyDeclared || member.DeclaredAccessibility != Accessibility.Public)
                    continue;
                var kind = curve is not null && SymbolEqualityComparer.Default.Equals(member.Type, curve) ? "curve"
                    : timelineRef is not null && SymbolEqualityComparer.Default.Equals(member.Type, timelineRef) ? "ref"
                    : timelineId is not null && SymbolEqualityComparer.Default.Equals(member.Type, timelineId) ? "id"
                    : "";
                fields.Add((member.Name, kind, member.Type.ToDisplayString(Full)));
            }
            writer.Append("[global::System.Serializable]\n");
            writer.Append("public sealed class ").Append(name).Append(" : global::Tl.Unity.TlClipData\n{\n");
            foreach (var field in fields)
            {
                if (field.kind == "curve")
                    writer.Append("public global::UnityEngine.AnimationCurve ").Append(field.name).Append(" = global::Tl.Unity.TlCurveAuthoring.Default();\n");
                else if (field.kind == "ref" || field.kind == "id")
                    writer.Append("public global::UnityEngine.Timeline.TimelineAsset ").Append(field.name).Append(";\n");
                else
                    writer.Append("public ").Append(field.type).Append(' ').Append(field.name).Append(";\n");
            }
            writer.Append("public override string MenuName => ").Append(SymbolDisplay.FormatLiteral(menu, true)).Append(";\n");
            writer.Append("public override global::System.Type ClipType => typeof(").Append(clip).Append(");\n");
            writer.Append("public override int ClipSize => global::Tl.Unity.TlClipBytes.SizeOf<").Append(clip).Append(">();\n");
            writer.Append("public override global::Tl.Unity.TlClipData CreateDefault() => new ").Append(name).Append("();\n");
            writer.Append("public ").Append(clip).Append(" ToClip()\n{\n");
            writer.Append("var clip = default(").Append(clip).Append(");\n");
            foreach (var field in fields)
            {
                writer.Append("clip.").Append(field.name).Append(" = ");
                writer.Append(field.kind == "curve" ? "global::Tl.Unity.TlCurveAuthoring.Sample(" + field.name + ")"
                    : field.kind == "ref" ? "global::Tl.Unity.TlClipData.TimelineOf(" + field.name + ")"
                    : field.kind == "id" ? "global::Tl.Unity.TlClipData.IdOf(" + field.name + ")"
                    : field.name).Append(";\n");
            }
            writer.Append("return clip;\n}\n");
            writer.Append("public override void WriteClip(byte[] destination, int offset)\n{\n");
            writer.Append("var clip = ToClip();\n");
            writer.Append("global::Tl.Unity.TlClipBytes.Write(in clip, destination, offset);\n}\n");
            writer.Append("public override void Bake(ref global::Tl.TlBaker baker)\n{\n");
            var any = false;
            foreach (var candidate in bakers)
                foreach (var face in candidate.AllInterfaces)
                    if (baker is not null && SymbolEqualityComparer.Default.Equals(face.OriginalDefinition, baker) && SymbolEqualityComparer.Default.Equals(face.TypeArguments[0], type))
                    {
                        if (!any)
                            writer.Append("var clip = ToClip();\n");
                        any = true;
                        writer.Append("default(").Append(candidate.ToDisplayString(Full)).Append(").Bake(ref baker, in clip);\n");
                    }
            writer.Append("}\n}\n");
        }

        static void EmitMenu(StringBuilder writer, INamedTypeSymbol type, string menu)
        {
            var mirror = MirrorName(type);
            writer.Append("[global::System.ComponentModel.DisplayName(").Append(SymbolDisplay.FormatLiteral(menu, true)).Append(")]\n");
            writer.Append("public sealed class ").Append(MenuName(type)).Append(" : global::Tl.Unity.TlMenuTrack\n{\n");
            writer.Append("public override global::Tl.Unity.TlClipData CreateTemplate() => new ").Append(mirror).Append("();\n}\n");
        }

        internal static string MenuName(INamedTypeSymbol type)
        {
            var mirror = MirrorName(type);
            return mirror.Substring(0, mirror.Length - "_TlData".Length) + "_TlMenu";
        }

        internal static string MirrorName(INamedTypeSymbol type)
        {
            var builder = new StringBuilder();
            var current = type;
            var parts = new Stack<string>();
            while (current is not null)
            {
                parts.Push(current.Name);
                current = current.ContainingType;
            }
            builder.Append(string.Join("_", parts));
            return builder.Append("_TlData").ToString();
        }
    }
}
