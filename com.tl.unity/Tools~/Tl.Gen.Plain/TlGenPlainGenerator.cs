using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using Tl.Gen.CSharp.Analysis;

namespace Tl.Gen.Plain
{
    [Generator(LanguageNames.CSharp)]
    public sealed class TlGenPlainGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var systems = context.SyntaxProvider.ForAttributeWithMetadataName(
                "Tl.TimelineSystemAttribute",
                static (node, _) => node is StructDeclarationSyntax,
                static (_, _) => true);
            var combined = systems.Collect().Combine(context.CompilationProvider);
            context.RegisterSourceOutput(combined, static (production, pair) => Generate(production, pair.Left.Length, pair.Right));
        }

        static void Generate(SourceProductionContext context, int systems, Compilation compilation)
        {
            if (systems == 0 || compilation is not CSharpCompilation csharp)
                return;
            var id = Sanitize(csharp.AssemblyName ?? "Game");
            var emitted = Tl.Gen.CSharp.SystemGeneration.Emit(csharp, id);
            foreach (var diagnostic in emitted.Diagnostics)
                context.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(diagnostic.Code, "Invalid timeline declaration", "{0}", "Tl.Generation", diagnostic.Code == "TLGEN98" ? DiagnosticSeverity.Warning : DiagnosticSeverity.Error, true),
                    Location(diagnostic), diagnostic.Message));
            if (emitted.Artifacts.Count == 0)
                return;
            foreach (var artifact in emitted.Artifacts)
                context.AddSource(artifact.RelativePath, SourceText.From(artifact.Content.Replace("\r\n", "\n"), new UTF8Encoding(false)));
            context.AddSource("TlSystems.Module.g.cs", SourceText.From(
                "// <auto-generated/>\nnamespace TlSystems\n{\ninternal static class TlModule\n{\ninternal static void Install() => TlModule_" + id + ".Install();\n}\n}\n",
                new UTF8Encoding(false)));
        }

        static string Sanitize(string name)
        {
            var chars = new char[name.Length];
            for (var i = 0; i < name.Length; i++)
                chars[i] = char.IsLetterOrDigit(name[i]) ? name[i] : '_';
            return new string(chars);
        }

        static Location Location(DeclarationDiagnostic diagnostic)
        {
            return diagnostic.SpanStart < 0 || diagnostic.File == null
                ? Microsoft.CodeAnalysis.Location.None
                : Microsoft.CodeAnalysis.Location.Create(
                    diagnostic.File,
                    new TextSpan(diagnostic.SpanStart, diagnostic.SpanLength),
                    new LinePositionSpan(
                        new LinePosition(diagnostic.Line - 1, diagnostic.Column - 1),
                        new LinePosition(diagnostic.EndLine - 1, diagnostic.EndColumn - 1)));
        }
    }
}
