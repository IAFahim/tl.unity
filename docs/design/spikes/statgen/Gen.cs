using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SpikeStateGen
{
    [Generator]
    public sealed class Gen : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var states = context.SyntaxProvider.ForAttributeWithMetadataName(
                "SpikeStateAttribute",
                static (node, _) => node is StructDeclarationSyntax,
                static (c, _) => (INamedTypeSymbol)c.TargetSymbol);
            var all = states.Collect().Combine(context.CompilationProvider);
            context.RegisterSourceOutput(all, static (spc, pair) =>
            {
                if (pair.Left.IsDefaultOrEmpty) return;
                var id = new string((pair.Right.AssemblyName ?? "Game").Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
                var parts = new StringBuilder("// <auto-generated/>\n");
                var reg = new StringBuilder();
                foreach (var s in pair.Left)
                {
                    var ns = s.ContainingNamespace.IsGlobalNamespace ? null : s.ContainingNamespace.ToDisplayString();
                    if (ns != null) parts.Append("namespace ").Append(ns).Append(" {\n");
                    parts.Append("partial struct ").Append(s.Name).Append(" : global::Unity.Entities.IComponentData { }\n");
                    if (ns != null) parts.Append("}\n");
                    reg.Append("global::UnityEngine.TypeManagerV2.RegisterComponentType(typeof(").Append(s.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(").TypeHandle);\n");
                }
                parts.Append("namespace TlUnityGenerated {\ninternal static class TlUnityTypeRegistration_").Append(id).Append(" {\ninternal static void Register() {\n");
                parts.Append("using var scope = global::UnityEngine.TypeManagerV2.BeginRegistration(typeof(TlUnityTypeRegistration_").Append(id).Append(").TypeHandle);\n");
                parts.Append(reg).Append("}\n}\n}\n");
                spc.AddSource("SpikeState.g.cs", SourceText.From(parts.ToString(), Encoding.UTF8));
            });
        }
    }
}
