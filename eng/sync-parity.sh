#!/usr/bin/env bash
# usage: eng/sync-parity.sh [--check]
# Copies tl's host-parity fixture (tests/Tl.Systems.Tests/Parity: the two domain sources, the library, the request script and the
# expected column bytes per tick) into com.tl.unity/Tests/Parity. The sources compile unchanged on both hosts; the data is embedded.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/external/tl-kinds/tests/Tl.Systems.Tests/Parity"
dst="$root/com.tl.unity/Tests/Parity"
[ -f "$src/ParityPack.cs" ] || { echo "external/tl-kinds has no Parity fixture: move it to a tl commit that carries tests/Tl.Systems.Tests/Parity" >&2; exit 1; }
stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
mkdir -p "$stage/Pack" "$stage/Game" "$stage/Tests"
tr -d '\r' < "$src/ParityPack.cs" > "$stage/Pack/ParityPack.cs"
tr -d '\r' < "$src/ParityGame.cs" > "$stage/Game/ParityGame.cs"
lines() { tr -d '\r' < "$1" | sed ':a;N;$!ba;s/\n/\\n/g'; }
{
  printf '%s\n' '// <auto-generated by eng/sync-parity.sh from tl tests/Tl.Systems.Tests/Parity; do not edit>' 'namespace ParityTests' '{' '    public static class ParityFixtureData' '    {'
  printf '        public static byte[] Library() => System.Convert.FromBase64String("%s");\n' "$(base64 -w0 "$src/parity.tlib")"
  printf '        public static string Script() => "%s";\n' "$(lines "$src/parity.script")"
  printf '        public static string Expected() => "%s";\n' "$(lines "$src/parity.expected")"
  printf '%s\n' '    }' '}'
} > "$stage/Tests/ParityFixtureData.cs"
files=("Pack/ParityPack.cs" "Game/ParityGame.cs" "Tests/ParityFixtureData.cs")
status=0
for file in "${files[@]}"; do
  if [ "${1:-}" = "--check" ]; then
    if cmp -s <(tr -d '\r' < "$stage/$file") <(tr -d '\r' < "$dst/$file" 2>/dev/null); then :; else echo "Tests/Parity/$file differs from tl" >&2; status=1; fi
  else
    cp "$stage/$file" "$dst/$file"
  fi
done
if [ "${1:-}" = "--check" ]; then
  [ "$status" = 0 ] && echo "Parity fixture matches tl"
  exit "$status"
fi
echo "Parity fixture synced"
