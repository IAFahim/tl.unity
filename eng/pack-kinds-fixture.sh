#!/usr/bin/env bash
# usage: TL_TLB=<tl or Tl.Bake.dll> eng/pack-kinds-fixture.sh <Library/ScriptAssemblies of a project that compiled the package tests> [--check]
# Packs com.tl.unity/Tests/Kinds/Timelines~ against the Unity test game assembly Tl.Unity.Kinds, so the
# fixture's pair keys are the Unity types' keys, and writes game.tlib, Timelines.g.cs and KindLibraryBytes.g.cs.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) windows=1 ;; *) windows=0 ;; esac
native() { if [ "$windows" = 1 ]; then cygpath -m "$1"; else printf '%s' "$1"; fi; }
assemblies="${1:?usage: eng/pack-kinds-fixture.sh <ScriptAssemblies folder> [--check]}"
[ -f "$assemblies/Tl.Unity.Kinds.dll" ] || { echo "no Tl.Unity.Kinds.dll in $assemblies" >&2; exit 1; }
tlb="${TL_TLB:?set TL_TLB to tl or Tl.Bake.dll}"
run() { case "$tlb" in *.dll) dotnet "$tlb" "$@" ;; *) "$tlb" "$@" ;; esac; }
kinds="$root/com.tl.unity/Tests/Kinds"
stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
unity="${UNITY:-$(python3 "$root/eng/unity_editor.py" editor)}"
case "$(uname -s)" in Darwin) engine="$(dirname "$(dirname "$unity")")/Managed/UnityEngine" ;; *) engine="$(dirname "$unity")/Data/Managed/UnityEngine" ;; esac
[ -d "$engine" ] || { echo "no engine assemblies at $engine; set UNITY" >&2; exit 1; }
cp "$assemblies"/*.dll "$stage"/
cp "$engine"/*.dll "$stage"/
run library "$(native "$kinds/Timelines~")" --assembly "$(native "$stage/Tl.Unity.Kinds.dll")" --out "$(native "$stage/game.tlib")" --ids "$(native "$stage/Timelines.g.cs")" --kinds "$(native "$stage/Kinds.g.cs")" --namespace KindGame >"$stage/tlb.log" 2>&1 || { cat "$stage/tlb.log" >&2; exit 1; }
{
  printf '%s\n' '// <auto-generated from Library/game.tlib; do not edit>' 'namespace KindGame' '{' '    public static class KindLibraryBytes' '    {' '        public static byte[] Bytes()' '        {'
  printf '            return System.Convert.FromBase64String("%s");\n' "$(base64 -w0 "$stage/game.tlib")"
  printf '%s\n' '        }' '    }' '}'
} > "$stage/KindLibraryBytes.g.cs"
status=0
for pair in "game.tlib:Timelines~/game.tlib" "Timelines.g.cs:Game/Timelines.g.cs" "Kinds.g.cs:Game/Kinds.g.cs" "KindLibraryBytes.g.cs:Game/KindLibraryBytes.g.cs"; do
  built="$stage/${pair%%:*}"; shipped="$kinds/${pair##*:}"
  if [ "${2:-}" = "--check" ]; then
    if cmp -s <(tr -d '\r' < "$built") <(tr -d '\r' < "$shipped"); then echo "${pair##*:} is current"; else echo "${pair##*:} is stale: run eng/pack-kinds-fixture.sh" >&2; status=1; fi
  else
    cp "$built" "$shipped"; echo "wrote ${pair##*:}"
  fi
done
exit $status
